#!/usr/bin/env python
"""Large test inputs kept in the test-data GitHub Release instead of git.

Input files of 2 MiB or more under ``tests/test_inputs/`` and ``examples/``
live as assets of one GitHub Release. ``tests/test_data.json`` lists each one
with its path, size, sha256, git blob ID and download URL, and a generated
block in ``.gitignore`` keeps the placed copies out of git.

``fetch`` puts every listed file at its path. It takes the file from the user
cache, else from git history by blob ID (a full clone works offline), else from
its URL, and checks the sha256 of every copy. pytest runs it once at start.

usage:
  python tools/test_data.py fetch [--require]
  python tools/test_data.py add PATH...
"""

from __future__ import annotations

import argparse
import hashlib
import http.client
import json
import os
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from collections.abc import Callable, Iterable, Iterator
from dataclasses import dataclass
from pathlib import Path
from typing import IO


PROJECT_ROOT = Path(__file__).resolve().parents[1]
MANIFEST_PATH = PROJECT_ROOT / "tests" / "test_data.json"
GITIGNORE_PATH = PROJECT_ROOT / ".gitignore"
RELEASE_REPOSITORY = "satoshikawato/gbdraw"
RELEASE_TAG = "test-data-2026-11"
GITIGNORE_BEGIN = "# BEGIN test data: generated by tools/test_data.py from tests/test_data.json"
GITIGNORE_END = "# END test data"
DOWNLOAD_ATTEMPTS = 3
CHUNK = 1 << 20


@dataclass(frozen=True)
class InputFile:
    """One input file that the test-data Release holds."""

    path: str
    size: int
    sha256: str
    git_blob: str
    url: str


def load_manifest(path: Path = MANIFEST_PATH) -> tuple[InputFile, ...]:
    rows = json.loads(path.read_text(encoding="utf-8"))["files"]
    return tuple(
        InputFile(
            path=row["path"],
            size=row["size"],
            sha256=row["sha256"],
            git_blob=row["gitBlob"],
            url=row["url"],
        )
        for row in rows
    )


def manifest_text(files: Iterable[InputFile]) -> str:
    rows = [
        {
            "path": item.path,
            "size": item.size,
            "sha256": item.sha256,
            "gitBlob": item.git_blob,
            "url": item.url,
        }
        for item in sorted(files, key=lambda item: item.path)
    ]
    return json.dumps({"files": rows}, indent=2) + "\n"


def gitignore_block(files: Iterable[InputFile]) -> str:
    paths = sorted(f"/{item.path}" for item in files)
    return "\n".join([GITIGNORE_BEGIN, *paths, GITIGNORE_END]) + "\n"


def with_gitignore_block(text: str, files: Iterable[InputFile]) -> str:
    """Return ``.gitignore`` text whose test-data block lists ``files``."""

    block = gitignore_block(files)
    if GITIGNORE_BEGIN not in text:
        return text.rstrip("\n") + "\n\n" + block
    head, rest = text.split(GITIGNORE_BEGIN, 1)
    tail = rest.split(GITIGNORE_END, 1)[1].lstrip("\n")
    return head + block + tail


def default_cache_dir() -> Path:
    configured = os.environ.get("GBDRAW_TEST_DATA_CACHE")
    if configured:
        return Path(configured)
    base = os.environ.get("XDG_CACHE_HOME") or Path.home() / ".cache"
    return Path(base) / "gbdraw" / "test-data"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(CHUNK):
            digest.update(chunk)
    return digest.hexdigest()


def _holds(path: Path, item: InputFile) -> bool:
    return (
        path.is_file()
        and path.stat().st_size == item.size
        and _sha256(path) == item.sha256
    )


def _store(cache: Path, item: InputFile, chunks: Iterable[bytes]) -> bool:
    """Write ``chunks`` to the cache entry of ``item`` if they hash to it."""

    cache.mkdir(parents=True, exist_ok=True)
    digest = hashlib.sha256()
    size = 0
    with tempfile.NamedTemporaryFile(dir=cache, delete=False) as handle:
        temporary = Path(handle.name)
        try:
            for chunk in chunks:
                digest.update(chunk)
                size += len(chunk)
                handle.write(chunk)
        except BaseException:
            temporary.unlink()
            raise
    if size != item.size or digest.hexdigest() != item.sha256:
        temporary.unlink()
        return False
    temporary.chmod(0o644)
    os.replace(temporary, cache / item.sha256)
    return True


def _read_exact(stream: IO[bytes], size: int) -> Iterator[bytes]:
    while size:
        chunk = stream.read(min(CHUNK, size))
        if not chunk:
            raise EOFError("git cat-file ended inside a blob")
        size -= len(chunk)
        yield chunk


def _from_git_history(items: list[InputFile], root: Path, cache: Path) -> None:
    """Copy the blobs of ``items`` that the local object store holds."""

    if not items:
        return
    try:
        process = subprocess.Popen(
            ["git", "-C", str(root), "cat-file", "--batch"],
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            env={**os.environ, "GIT_NO_LAZY_FETCH": "1"},
        )
    except OSError:
        return
    assert process.stdin is not None and process.stdout is not None
    try:
        process.stdin.write("".join(f"{item.git_blob}\n" for item in items).encode())
        process.stdin.close()
    except BrokenPipeError:
        # git already exited: no repository here, or one it refuses to read.
        pass
    by_blob = {item.git_blob: item for item in items}
    try:
        for header in iter(process.stdout.readline, b""):
            fields = header.split()
            if len(fields) != 3 or fields[1] != b"blob":
                continue
            _store(cache, by_blob[fields[0].decode()], _read_exact(process.stdout, int(fields[2])))
            process.stdout.read(1)
    except EOFError:
        process.kill()
    process.wait()


def _download(item: InputFile, cache: Path, log: Callable[[str], None]) -> None:
    for attempt in range(1, DOWNLOAD_ATTEMPTS + 1):
        try:
            with urllib.request.urlopen(item.url, timeout=60) as response:
                if _store(cache, item, iter(lambda: response.read(CHUNK), b"")):
                    return
            log(f"test data: {item.path}: the download does not match the manifest")
        except (OSError, http.client.HTTPException) as error:
            log(f"test data: {item.path}: download attempt {attempt} failed: {error}")


def _place(entry: Path, destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_name(f".{destination.name}.{os.getpid()}.tmp")
    temporary.unlink(missing_ok=True)
    try:
        os.link(entry, temporary)
    except OSError:
        shutil.copyfile(entry, temporary)
    os.replace(temporary, destination)


def _log(message: str) -> None:
    print(message, file=sys.stderr, flush=True)


def fetch(
    files: Iterable[InputFile] | None = None,
    *,
    root: Path = PROJECT_ROOT,
    cache: Path | None = None,
    require: bool = False,
    log: Callable[[str], None] = _log,
) -> tuple[InputFile, ...]:
    """Put each input at its path and return the ones that could not be found.

    With ``require``, raise ``FileNotFoundError`` instead of returning any.
    """

    items = load_manifest() if files is None else tuple(files)
    pending = [item for item in items if not _holds(root / item.path, item)]
    if not pending:
        return ()
    cache = default_cache_dir() if cache is None else cache
    log(f"test data: placing {len(pending)} input file(s) from {cache}, git history or the test-data Release")
    _from_git_history([item for item in pending if not _holds(cache / item.sha256, item)], root, cache)
    for item in pending:
        if not _holds(cache / item.sha256, item):
            _download(item, cache, log)
    missing = []
    for item in pending:
        entry = cache / item.sha256
        if _holds(entry, item):
            _place(entry, root / item.path)
        else:
            missing.append(item)
    if missing and require:
        raise FileNotFoundError(
            "Test inputs could not be fetched: "
            + ", ".join(item.path for item in missing)
            + ". Run python tools/test_data.py fetch with network access."
        )
    return tuple(missing)


def _git_blob(path: Path) -> str:
    return subprocess.run(
        ["git", "-C", str(PROJECT_ROOT), "hash-object", "--", str(path)],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()


def add(paths: Iterable[Path], *, tag: str = RELEASE_TAG) -> None:
    """Upload ``paths`` to the test-data Release and list them in the manifest.

    Asset names start with the sha256, so a changed file becomes a new asset
    and older commits keep resolving theirs. Needs ``gh`` with write access.
    """

    added = []
    with tempfile.TemporaryDirectory() as staging:
        for path in paths:
            source = path.resolve()
            sha256 = _sha256(source)
            asset = Path(staging) / f"{sha256[:12]}-{source.name}"
            shutil.copyfile(source, asset)
            subprocess.run(
                ["gh", "release", "upload", tag, str(asset), "--clobber", "--repo", RELEASE_REPOSITORY],
                check=True,
            )
            added.append(
                InputFile(
                    path=source.relative_to(PROJECT_ROOT).as_posix(),
                    size=source.stat().st_size,
                    sha256=sha256,
                    git_blob=_git_blob(source),
                    url=f"https://github.com/{RELEASE_REPOSITORY}/releases/download/{tag}/{asset.name}",
                )
            )
    paths_added = {item.path for item in added}
    files = [item for item in load_manifest() if item.path not in paths_added] + added
    MANIFEST_PATH.write_text(manifest_text(files), encoding="utf-8")
    GITIGNORE_PATH.write_text(
        with_gitignore_block(GITIGNORE_PATH.read_text(encoding="utf-8"), files),
        encoding="utf-8",
    )
    print("Run git rm --cached on any of these paths that git still tracks.")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    fetch_parser = commands.add_parser("fetch", help="Put every listed input at its path.")
    fetch_parser.add_argument("--require", action="store_true", help="Exit with status 1 if an input is missing.")
    add_parser = commands.add_parser("add", help="Upload inputs to the test-data Release and list them.")
    add_parser.add_argument("paths", nargs="+", type=Path)
    args = parser.parse_args(argv)
    if args.command == "add":
        add(args.paths)
        return 0
    missing = fetch()
    for item in missing:
        _log(f"test data: missing {item.path}")
    return 1 if missing and args.require else 0


if __name__ == "__main__":
    raise SystemExit(main())
